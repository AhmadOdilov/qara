export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && (LANGS as readonly string[]).includes(value);
}

/**
 * Telegram `language_code` ("uz", "ru-RU", "en-GB" …) ni ilova tiliga moslash.
 * Nomos til uchun standart — o'zbekcha.
 */
export function langFromTelegram(code: string | null | undefined): Lang {
  const base = (code ?? "").split("-")[0].toLowerCase();
  return isLang(base) ? base : "uz";
}

/** "{name}" kabi o'rin egallovchilarni to'ldiradi. */
export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? values[key] : match,
  );
}
